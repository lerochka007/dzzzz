#исходный список чисел для сортировки
a = [12, 4, 9, 1, 6, 3]
#выводим исходный список на экран
print("Исходный список:", a)
#сохраняем длину списка в отдельную переменную
n = len(a)
#текущий размер подсписков для слияния, начинаем с единицы
k = 1
#крутим цикл, пока размер блока меньше длины всего списка
while k < n:
    #начинаем с самого первого элемента
    l = 0
    #проходим по всему списку порциями
    while l < n - 1:
        #определяем границу середины текущего блока
        m = min(l + k - 1, n - 1)
        #определяем правую границу текущего блока
        r = min(l + 2 * k - 1, n - 1)
        #временный список для слияния двух отсортированных частей
        b = []
        #указатель на элементы левой половины
        i = l
        #указатель на элементы правой половины
        j = m + 1
        #сравниваем элементы из обеих половин и собираем по порядку
        while i <= m and j <= r:
            if a[i] <= a[j]:
                b.append(a[i])
                i += 1
            else:
                b.append(a[j])
                j += 1      
        #если в левой половине что-то осталось, докидываем в буфер
        while i <= m:
            b.append(a[i])
            i += 1  
        #если в правой половине что-то осталось, докидываем в буфер
        while j <= r:
            b.append(a[j])
            j += 1           
        #перезаписываем отсортированный кусок обратно в основной список
        for x in range(len(b)):
            a[l + x] = b[x]           
        #переходим к следующей паре блоков
        l += 2 * k
    #увеличиваем размер блока в два раза для следующего прохода
    k *= 2
#выводим результат на экран
print("Отсортированный список:", a)